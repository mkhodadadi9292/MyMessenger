SNIFF_BYTES = 64

_EQUIVALENT_MIME_TYPES: dict[str, frozenset[str]] = {
    "audio/mpeg": frozenset({"audio/mpeg", "audio/mp3"}),
}


def sniff_mime_type(head: bytes) -> str | None:
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if head.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if head.startswith((b"GIF87a", b"GIF89a")):
        return "image/gif"
    if head.startswith(b"RIFF") and head[8:12] == b"WEBP":
        return "image/webp"
    if head.startswith(b"RIFF") and head[8:12] == b"WAVE":
        return "audio/wav"
    if head[4:8] == b"ftyp":
        return "video/quicktime" if head[8:12] == b"qt  " else "video/mp4"
    if head.startswith(b"\x1a\x45\xdf\xa3"):
        return "video/webm"
    if head.startswith(b"OggS"):
        return "audio/ogg"
    if head.startswith(b"ID3") or (len(head) > 1 and head[0] == 0xFF and head[1] & 0xE0 == 0xE0):
        return "audio/mpeg"
    return None


def content_matches_declared_type(head: bytes, declared: str) -> bool:
    sniffed = sniff_mime_type(head)
    if sniffed is None:
        return False
    return declared in _EQUIVALENT_MIME_TYPES.get(sniffed, frozenset({sniffed}))
